#!/usr/bin/env python3
"""Render "Pay now" buttons from data/packages.json into every HTML page.

Markers (idempotent — everything between a marker pair is regenerated):
  <!-- pay:KEY --><!-- /pay -->                 full-width "Pay now — $X" button
  <!-- payrow:KEY1,KEY2,KEY3 --><!-- /payrow --> compact row: "Pay now: [Tier 1 $X] [Tier 2 $Y]"

It also writes /pay-links.js (window.MMA_PACKAGES) so the thank-you page can
show which package was bought. Run after editing data/packages.json.
"""
import json, os, re, sys, html

ROOT = os.path.dirname(os.path.abspath(__file__))
data = json.load(open(os.path.join(ROOT, "data", "packages.json")))
PK = data["packages"]

def money(p):
    return f"${p:,.2f}" if round(p) != p else f"${int(p):,}"

def link(key):
    if key not in PK:
        sys.exit(f"pay_buttons: unknown package key '{key}'")
    url = PK[key].get("payment_link")
    if not url:
        sys.exit(f"pay_buttons: package '{key}' has no payment_link yet")
    return url, PK[key]

def per(p):
    return "/mo" if p.get("interval") == "month" else ""

def pay(key):
    url, p = link(key)
    verb = "Subscribe" if p.get("interval") else "Pay now"
    prep = "to" if p.get("interval") else "for"
    return (f'<a class="pay-btn" href="{html.escape(url)}" rel="nofollow noopener" '
            f'data-pay="{key}" aria-label="{verb} {prep} {html.escape(p["name"])} — {money(p["price"])}{per(p)}">'
            f'{verb} — {money(p["price"])}{per(p)}</a>'
            f'<span class="pay-note">Secure checkout by Stripe{" · cancel anytime" if p.get("interval") else ""}</span>')

def payrow(keys):
    parts = []
    for k in keys:
        url, p = link(k)
        parts.append(f'<a class="pay-chip" href="{html.escape(url)}" rel="nofollow noopener" data-pay="{k}" '
                     f'aria-label="Pay now for {html.escape(p["name"])}">{html.escape(p["short"])} · {money(p["price"])}{per(p)}</a>')
    return '<div class="pay-row"><span class="pay-row-label">Pay now:</span>' + "".join(parts) + '</div>'

PAY = re.compile(r"<!-- pay:([a-z0-9_]+) -->.*?<!-- /pay -->", re.S)
ROW = re.compile(r"<!-- payrow:([a-z0-9_,]+) -->.*?<!-- /payrow -->", re.S)

changed = 0
for dp, dn, fn in os.walk(ROOT):
    dn[:] = [d for d in dn if not d.startswith(".") and d != "node_modules"]
    for f in fn:
        if not f.endswith(".html"):
            continue
        path = os.path.join(dp, f)
        s = open(path, encoding="utf-8").read()
        if "<!-- pay" not in s:
            continue
        n = PAY.sub(lambda m: f"<!-- pay:{m.group(1)} -->{pay(m.group(1))}<!-- /pay -->", s)
        n = ROW.sub(lambda m: f"<!-- payrow:{m.group(1)} -->{payrow(m.group(1).split(','))}<!-- /payrow -->", n)
        if n != s:
            open(path, "w", encoding="utf-8").write(n)
            changed += 1

public = {k: {"name": v["name"], "price": v["price"], "intake": v.get("intake", "general"), **({"interval": v["interval"]} if v.get("interval") else {})} for k, v in PK.items()}
open(os.path.join(ROOT, "pay-links.js"), "w").write(
    "// Generated by pay_buttons.py from data/packages.json — do not edit by hand.\n"
    "window.MMA_PACKAGES = " + json.dumps(public, ensure_ascii=False, indent=2) + ";\n")
print(f"pay_buttons: updated {changed} page(s), {len(PK)} package(s)")
